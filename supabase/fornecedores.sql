create table if not exists public.fornecedores_operacionais (
    id bigint generated by default as identity primary key,
    nome text not null,
    categoria text not null,
    cidade text not null,
    estado varchar(2) not null,
    telefone text not null default '',
    endereco_completo text not null default '',
    link_google_maps text not null default '',
    observacoes_4sas text not null default '',
    google_place_id text,
    nota_google numeric(3, 2),
    qtd_avaliacoes integer,
    created_at timestamptz not null default now()
);

alter table public.fornecedores_operacionais
    add column if not exists google_place_id text;
create unique index if not exists fornecedores_google_place_id_key
    on public.fornecedores_operacionais (google_place_id);

alter table public.fornecedores_operacionais enable row level security;

revoke all on table public.fornecedores_operacionais
    from public, anon, authenticated;
grant select, insert on table public.fornecedores_operacionais to authenticated;

drop policy if exists "Suppliers readable by authenticated users"
    on public.fornecedores_operacionais;
create policy "Suppliers readable by authenticated users"
    on public.fornecedores_operacionais
    for select
    to authenticated
    using (auth.uid() is not null);

drop policy if exists "Suppliers insertable by authenticated users"
    on public.fornecedores_operacionais;
create policy "Suppliers insertable by authenticated users"
    on public.fornecedores_operacionais
    for insert
    to authenticated
    with check (auth.uid() is not null);

do $$
declare
    id_sequence text;
begin
    id_sequence := pg_get_serial_sequence(
        'public.fornecedores_operacionais',
        'id'
    );
    if id_sequence is not null then
        execute format(
            'grant usage, select on sequence %s to authenticated',
            id_sequence::regclass
        );
    end if;
end;
$$;